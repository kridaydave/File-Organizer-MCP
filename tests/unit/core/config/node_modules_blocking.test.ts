import { describe, it, expect } from '@jest/globals';
import { getAlwaysBlockedPatterns } from '../../../../src/core/config/security.js';

describe('node_modules blocking (BUG-90)', () => {
  const patterns = getAlwaysBlockedPatterns();
  const isBlocked = (p: string) => patterns.some((re) => re.test(p));

  it('blocks actual node_modules directory', () => {
    expect(isBlocked('/project/node_modules')).toBe(true);
    expect(isBlocked('/project/node_modules/package/index.js')).toBe(true);
    expect(isBlocked('node_modules')).toBe(true);
    expect(isBlocked('src/node_modules/lib')).toBe(true);
  });

  it('allows paths containing node_modules as substring but not as directory component', () => {
    expect(isBlocked('/allowed/my_node_modules_backup/file.txt')).toBe(false);
    expect(isBlocked('/allowed/node_modules_backup')).toBe(false);
    expect(isBlocked('my_node_modules_backup/file.txt')).toBe(false);
  });

  it('blocks node_modules with both separator styles', () => {
    expect(isBlocked('a\\node_modules\\b')).toBe(true);
    expect(isBlocked('a/node_modules/b')).toBe(true);
    expect(isBlocked('C:\\project\\node_modules\\file.js')).toBe(true);
  });
});
